package com.gojiramod.client;

import com.gojiramod.Gojira;
import com.gojiramod.GojiraMod;
import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.util.Mth;

/**
 * Gojira: a detailed, upright, dinosaur-like kaiju. Thick legs (thigh, shin, toed foot), a heavy barrel chest, short
 * clawed arms (upper arm, forearm, fingered hand), a thick neck, a big rounded head with brow, nostrils, eyes, teeth and a
 * jaw that opens, a six-part tapering tail that sways, and three rows of jagged pale maple-leaf dorsal plates.
 * Animations: walk, breathe, look, stomp, roar/beam jaw, plate glow, swim, claw swipe, tail whip and death. The boxes are generated by tools/gojira.py ({@link GojiraModelLayer}); the renderer scales it to 164/3 = 54.67 blocks tall.
 */
public class GojiraModel extends EntityModel<GojiraRenderState> {
	public static final ModelLayerLocation LAYER = new ModelLayerLocation(GojiraMod.id("gojira"), "main");
	private final ModelPart rightLeg, leftLeg, rightShin, leftShin, hips, body, neck, head, jaw, rightArm, leftArm, rightForearm, leftForearm;
	private final ModelPart tail1, tail2, tail3, tail4, tail5, tail6;

	public GojiraModel(final ModelPart root) {
		super(root);
		this.rightLeg = root.getChild("right_leg");
		this.leftLeg = root.getChild("left_leg");
		this.rightShin = this.rightLeg.getChild("right_shin");
		this.leftShin = this.leftLeg.getChild("left_shin");
		this.hips = root.getChild("hips");
		this.body = this.hips.getChild("body");
		this.neck = this.body.getChild("neck");
		this.head = this.neck.getChild("head");
		this.jaw = this.head.getChild("jaw");
		this.rightArm = this.body.getChild("right_arm");
		this.leftArm = this.body.getChild("left_arm");
		this.rightForearm = this.rightArm.getChild("right_forearm");
		this.leftForearm = this.leftArm.getChild("left_forearm");
		this.tail1 = this.hips.getChild("tail1");
		this.tail2 = this.tail1.getChild("tail2");
		this.tail3 = this.tail2.getChild("tail3");
		this.tail4 = this.tail3.getChild("tail4");
		this.tail5 = this.tail4.getChild("tail5");
		this.tail6 = this.tail5.getChild("tail6");
	}

	public static LayerDefinition createBodyLayer() {
		return GojiraModelLayer.create();
	}

	@Override
	public void setupAnim(final GojiraRenderState state) {
		super.setupAnim(state); // resets every part to its default pose first
		float walk = state.walkAnimationPos, speed = Math.min(state.walkAnimationSpeed, 1.0F), t = state.ageInTicks;
		float swim = state.swimAmount, land = 1.0F - swim;
		// slow, heavy, earth-shaking walk (fades out while swimming)
		float stride = Mth.cos(walk * 0.25F) * 0.45F * speed * land;
		this.rightLeg.xRot = stride;
		this.leftLeg.xRot = -stride;
		// knees bend as each leg swings back up
		this.rightShin.xRot += Math.max(0.0F, Mth.sin(walk * 0.25F)) * 0.35F * speed * land;
		this.leftShin.xRot += Math.max(0.0F, -Mth.sin(walk * 0.25F)) * 0.35F * speed * land;
		this.hips.zRot = Mth.sin(walk * 0.25F) * 0.04F * speed * land;
		this.hips.y += Math.abs(Mth.sin(walk * 0.25F)) * -0.6F * speed * land;
		// breathing and tail sway
		float breathe = Mth.sin(t * 0.04F) * 0.02F;
		this.body.xRot += breathe;
		this.rightArm.xRot += Mth.sin(t * 0.05F) * 0.05F;
		this.leftArm.xRot += Mth.sin(t * 0.05F + 1.0F) * 0.05F;
		this.rightForearm.xRot += Mth.sin(t * 0.05F + 0.6F) * 0.06F - stride * 0.15F;
		this.leftForearm.xRot += Mth.sin(t * 0.05F + 1.6F) * 0.06F + stride * 0.15F;
		float sway = (Mth.sin(t * 0.03F) * 0.12F + Mth.sin(walk * 0.25F) * 0.15F * speed) * land;
		this.tail1.yRot = sway * 0.6F;
		this.tail2.yRot = sway * 0.8F;
		this.tail3.yRot = sway;
		this.tail4.yRot = sway * 1.2F;
		this.tail5.yRot = sway * 1.35F;
		this.tail6.yRot = sway * 1.5F;
		// look around (a little: it's a big animal)
		this.neck.yRot = Mth.clamp(state.yRot, -40.0F, 40.0F) * Mth.DEG_TO_RAD * 0.4F;
		this.head.yRot = Mth.clamp(state.yRot, -40.0F, 40.0F) * Mth.DEG_TO_RAD * 0.6F;
		this.head.xRot += Mth.clamp(state.xRot, -30.0F, 40.0F) * Mth.DEG_TO_RAD * 0.5F * land;

		// SWIM: the whole body tips forward to lie flat like a crocodile, the head lifts to look ahead, the tail does big
		// side-to-side sweeps (a wave running down it), the legs kick behind and the arms tuck in against the chest
		if (swim > 0.0F) {
			float stroke = t * 0.16F;
			this.root().xRot += 1.15F * swim;
			this.root().y += 6.0F * swim;
			this.neck.xRot -= 0.45F * swim;
			this.head.xRot -= 0.55F * swim;
			this.hips.zRot += Mth.sin(stroke) * 0.06F * swim;
			this.body.yRot += Mth.sin(stroke - 0.6F) * -0.06F * swim;
			this.tail1.yRot += Mth.sin(stroke - 0.4F) * 0.25F * swim;
			this.tail2.yRot += Mth.sin(stroke - 0.8F) * 0.3F * swim;
			this.tail3.yRot += Mth.sin(stroke - 1.2F) * 0.35F * swim;
			this.tail4.yRot += Mth.sin(stroke - 1.6F) * 0.4F * swim;
			this.tail5.yRot += Mth.sin(stroke - 2.0F) * 0.45F * swim;
			this.tail6.yRot += Mth.sin(stroke - 2.4F) * 0.5F * swim;
			this.tail1.xRot -= 0.75F * swim; // the tail lifts to lie flat in line with the body
			float kick = Mth.sin(stroke * 1.3F) * 0.55F * swim;
			this.rightLeg.xRot += 0.5F * swim + kick;
			this.leftLeg.xRot += 0.5F * swim - kick;
			this.rightShin.xRot += (0.9F + Math.max(0.0F, kick)) * swim;
			this.leftShin.xRot += (0.9F + Math.max(0.0F, -kick)) * swim;
			this.rightArm.xRot += 0.9F * swim;
			this.leftArm.xRot += 0.9F * swim;
			this.rightArm.zRot -= 0.15F * swim;
			this.leftArm.zRot += 0.15F * swim;
			this.rightForearm.xRot -= 1.0F * swim;
			this.leftForearm.xRot -= 1.0F * swim;
		}

		// stomp: the right leg lifts high, the body leans back, then the foot SLAMS down
		float st = state.stompProgress;
		if (st > 0.0F) {
			float lift = st < 0.6F ? st / 0.6F : Math.max(0.0F, 1.0F - (st - 0.6F) / 0.08F);
			this.rightLeg.xRot = -1.1F * lift;
			this.rightShin.xRot += 0.9F * lift;
			this.body.xRot -= 0.15F * lift;
			this.tail1.xRot += 0.15F * lift;
			this.rightArm.xRot -= 0.4F * lift;
			this.leftArm.xRot -= 0.4F * lift;
			this.rightForearm.xRot -= 0.3F * lift;
			this.leftForearm.xRot -= 0.3F * lift;
		}

		// CLAW SWIPE: the body twists back and the right arm rises high with claws spread (wind-up), then it rakes down and
		// across in front of it, and slowly comes back
		float sw = state.swipeProgress;
		if (sw > 0.0F) {
			float hit = (float) Gojira.SWIPE_WINDUP / Gojira.SWIPE_ANIM;
			float raise = sw < hit ? Mth.sin(sw / hit * Mth.HALF_PI) : 0.0F;
			float strike = sw < hit ? 0.0F : (sw < hit + 0.15F ? (sw - hit) / 0.15F : 1.0F);
			float recover = sw < hit + 0.15F ? 1.0F : Math.max(0.0F, 1.0F - (sw - hit - 0.15F) / (0.85F - hit));
			float twist = (-0.3F * raise + 0.35F * strike) * recover;
			this.body.yRot += twist;
			this.neck.yRot -= twist * 0.5F;
			this.rightArm.xRot += (-1.1F * raise + 0.6F * strike) * recover;
			this.rightArm.zRot += (0.6F * raise - 0.3F * strike) * recover;
			this.rightForearm.xRot += (-0.5F * raise + 0.2F * strike) * recover;
			this.leftArm.xRot += -0.4F * (raise + strike) * recover;
			this.jaw.xRot += 0.35F * (raise + strike) * recover; // snarl
			this.tail1.yRot -= twist * 0.6F;
		}

		// TAIL WHIP: the hips turn and the tail coils to one side, then lashes all the way across behind it
		float wh = state.whipProgress;
		if (wh > 0.0F) {
			float hit = (float) Gojira.WHIP_WINDUP / Gojira.WHIP_ANIM;
			float coil = wh < hit ? Mth.sin(wh / hit * Mth.HALF_PI) : 0.0F;
			float lash = wh < hit ? 0.0F : (wh < hit + 0.15F ? (wh - hit) / 0.15F : 1.0F);
			float recover = wh < hit + 0.15F ? 1.0F : Math.max(0.0F, 1.0F - (wh - hit - 0.15F) / (0.85F - hit));
			float side = (-1.0F * coil + 1.0F * lash) * recover; // -1 coiled left .. +1 lashed right
			this.hips.yRot += side * 0.25F;
			this.body.yRot -= side * 0.15F;
			this.tail1.yRot += side * 0.25F;
			this.tail2.yRot += side * 0.22F;
			this.tail3.yRot += side * 0.2F;
			this.tail4.yRot += side * 0.18F;
			this.tail5.yRot += side * 0.16F;
			this.tail6.yRot += side * 0.14F;
			this.tail1.xRot += 0.12F * (coil + lash) * recover; // the tail lifts a little off the ground as it swings
		}

		// roar / beam: head rears back slightly and the jaw opens wide
		float jaw = state.jawOpen;
		this.jaw.xRot += 0.75F * jaw;
		this.head.xRot -= 0.25F * jaw;
		this.neck.xRot -= 0.1F * state.spikeGlow;

		// DEATH: the renderer tips the whole body over onto its side; here the knees buckle, the arms go limp, the head rears
		// back for a last roar and then drops, and the tail sags
		float dp = state.deathProgress;
		if (dp > 0.0F) {
			float buckle = Math.min(1.0F, dp / 0.5F);
			this.rightShin.xRot += 0.6F * buckle;
			this.leftShin.xRot += 0.45F * buckle;
			this.rightLeg.xRot -= 0.3F * buckle;
			this.leftLeg.xRot -= 0.2F * buckle;
			this.rightArm.zRot -= 0.5F * buckle;
			this.leftArm.zRot += 0.5F * buckle;
			this.rightForearm.xRot += 0.4F * buckle;
			this.leftForearm.xRot += 0.4F * buckle;
			float rear = dp < 0.3F ? dp / 0.3F : Math.max(0.0F, 1.0F - (dp - 0.3F) / 0.3F);
			this.head.xRot -= 0.35F * rear;
			this.neck.xRot += 0.3F * Math.max(0.0F, (dp - 0.4F) / 0.6F);
			this.tail1.xRot -= 0.15F * buckle;
			this.tail3.xRot -= 0.1F * buckle;
		}
	}
}
