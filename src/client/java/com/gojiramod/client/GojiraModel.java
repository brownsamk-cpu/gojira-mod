package com.gojiramod.client;

import com.gojiramod.GojiraMod;
import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.util.Mth;

/**
 * Gojira: a detailed, upright, dinosaur-like kaiju. Thick legs (thigh, shin, toed foot), a heavy barrel chest, short
 * clawed arms (upper arm, forearm, fingered hand), a thick neck, a big rounded head with brow, nostrils, eyes, teeth and a
 * jaw that opens, a six-part tapering tail that sways, and three rows of jagged pale maple-leaf dorsal plates. The boxes are generated by tools/gojira.py ({@link GojiraModelLayer}); the renderer scales it to 164/3 = 54.67 blocks tall.
 */
public class GojiraModel extends EntityModel<GojiraRenderState> {
	public static final ModelLayerLocation LAYER = new ModelLayerLocation(GojiraMod.id("gojira"), "main");
	private final ModelPart rightLeg, leftLeg, rightShin, leftShin, hips, body, neck, head, jaw, rightArm, leftArm, rightForearm, leftForearm;
	private final ModelPart tail1, tail2, tail3, tail4, tail5, tail6;

	public GojiraModel(final ModelPart root) {
		super(root);
		this.rightLeg = root.getChild("right_leg");
		this.leftLeg = root.getChild("left_leg");
		this.rightShin = this.rightLeg.getChild("right_shin");
		this.leftShin = this.leftLeg.getChild("left_shin");
		this.hips = root.getChild("hips");
		this.body = this.hips.getChild("body");
		this.neck = this.body.getChild("neck");
		this.head = this.neck.getChild("head");
		this.jaw = this.head.getChild("jaw");
		this.rightArm = this.body.getChild("right_arm");
		this.leftArm = this.body.getChild("left_arm");
		this.rightForearm = this.rightArm.getChild("right_forearm");
		this.leftForearm = this.leftArm.getChild("left_forearm");
		this.tail1 = this.hips.getChild("tail1");
		this.tail2 = this.tail1.getChild("tail2");
		this.tail3 = this.tail2.getChild("tail3");
		this.tail4 = this.tail3.getChild("tail4");
		this.tail5 = this.tail4.getChild("tail5");
		this.tail6 = this.tail5.getChild("tail6");
	}

	public static LayerDefinition createBodyLayer() {
		return GojiraModelLayer.create();
	}

	@Override
	public void setupAnim(final GojiraRenderState state) {
		super.setupAnim(state); // resets every part to its default pose first
		float walk = state.walkAnimationPos, speed = Math.min(state.walkAnimationSpeed, 1.0F), t = state.ageInTicks;
		// slow, heavy, earth-shaking walk
		float stride = Mth.cos(walk * 0.25F) * 0.45F * speed;
		this.rightLeg.xRot = stride;
		this.leftLeg.xRot = -stride;
		// knees bend as each leg swings back up
		this.rightShin.xRot += Math.max(0.0F, Mth.sin(walk * 0.25F)) * 0.35F * speed;
		this.leftShin.xRot += Math.max(0.0F, -Mth.sin(walk * 0.25F)) * 0.35F * speed;
		this.hips.zRot = Mth.sin(walk * 0.25F) * 0.04F * speed;
		this.hips.y += Math.abs(Mth.sin(walk * 0.25F)) * -0.6F * speed;
		// breathing and tail sway
		float breathe = Mth.sin(t * 0.04F) * 0.02F;
		this.body.xRot += breathe;
		this.rightArm.xRot += Mth.sin(t * 0.05F) * 0.05F;
		this.leftArm.xRot += Mth.sin(t * 0.05F + 1.0F) * 0.05F;
		this.rightForearm.xRot += Mth.sin(t * 0.05F + 0.6F) * 0.06F - stride * 0.15F;
		this.leftForearm.xRot += Mth.sin(t * 0.05F + 1.6F) * 0.06F + stride * 0.15F;
		float sway = Mth.sin(t * 0.03F) * 0.12F + Mth.sin(walk * 0.25F) * 0.15F * speed;
		this.tail1.yRot = sway * 0.6F;
		this.tail2.yRot = sway * 0.8F;
		this.tail3.yRot = sway;
		this.tail4.yRot = sway * 1.2F;
		this.tail5.yRot = sway * 1.35F;
		this.tail6.yRot = sway * 1.5F;
		// look around (a little: it's a big animal)
		this.neck.yRot = Mth.clamp(state.yRot, -40.0F, 40.0F) * Mth.DEG_TO_RAD * 0.4F;
		this.head.yRot = Mth.clamp(state.yRot, -40.0F, 40.0F) * Mth.DEG_TO_RAD * 0.6F;
		this.head.xRot += Mth.clamp(state.xRot, -30.0F, 40.0F) * Mth.DEG_TO_RAD * 0.5F;
		// stomp: the right leg lifts high, the body leans back, then the foot SLAMS down
		float st = state.stompProgress;
		if (st > 0.0F) {
			float lift = st < 0.6F ? st / 0.6F : Math.max(0.0F, 1.0F - (st - 0.6F) / 0.08F);
			this.rightLeg.xRot = -1.1F * lift;
			this.rightShin.xRot += 0.9F * lift;
			this.body.xRot -= 0.15F * lift;
			this.tail1.xRot += 0.15F * lift;
			this.rightArm.xRot -= 0.4F * lift;
			this.leftArm.xRot -= 0.4F * lift;
			this.rightForearm.xRot -= 0.3F * lift;
			this.leftForearm.xRot -= 0.3F * lift;
		}
		// roar / beam: head rears back slightly and the jaw opens wide
		float jaw = state.jawOpen;
		this.jaw.xRot = 0.75F * jaw;
		this.head.xRot -= 0.25F * jaw;
		this.neck.xRot -= 0.1F * state.spikeGlow;
	}
}
